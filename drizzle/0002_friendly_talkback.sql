CREATE TABLE `property_listings` (
	`id` text PRIMARY KEY NOT NULL,
	`owner_id` text NOT NULL,
	`deal_type` text NOT NULL,
	`property_type` text NOT NULL,
	`title` text NOT NULL,
	`description` text NOT NULL,
	`cep` text NOT NULL,
	`street` text NOT NULL,
	`address_number` text NOT NULL,
	`complement` text,
	`neighborhood` text NOT NULL,
	`city` text NOT NULL,
	`state` text NOT NULL,
	`sale_price` integer,
	`rent_price` integer,
	`condominium_fee` integer DEFAULT 0 NOT NULL,
	`monthly_iptu` integer DEFAULT 0 NOT NULL,
	`bedrooms` integer DEFAULT 0 NOT NULL,
	`bathrooms` integer DEFAULT 0 NOT NULL,
	`parking_spaces` integer DEFAULT 0 NOT NULL,
	`area_m2` integer NOT NULL,
	`furnished` integer DEFAULT false NOT NULL,
	`pet_friendly` integer DEFAULT false NOT NULL,
	`acquisition_methods_json` text DEFAULT '[]' NOT NULL,
	`rental_guarantees_json` text DEFAULT '[]' NOT NULL,
	`cover_image_key` text,
	`status` text DEFAULT 'ativo' NOT NULL,
	`created_at` text DEFAULT CURRENT_TIMESTAMP NOT NULL,
	`updated_at` text DEFAULT CURRENT_TIMESTAMP NOT NULL,
	FOREIGN KEY (`owner_id`) REFERENCES `user_profiles`(`id`) ON UPDATE no action ON DELETE cascade
);
